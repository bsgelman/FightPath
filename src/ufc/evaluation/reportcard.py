"""Generate backtest report card markdown."""
from __future__ import annotations

import math
from datetime import date
from pathlib import Path


def write_report(metrics: dict, save_path: Path) -> None:
    """Write a markdown report card from metrics dict."""
    save_path.parent.mkdir(parents=True, exist_ok=True)

    lines = [
        f"# UFC Model Backtest Report — {date.today()}",
        "",
        "## Winner Model (Test Set)",
        "",
        f"| Metric | Value | Target |",
        f"|--------|-------|--------|",
        f"| Accuracy | {metrics.get('accuracy', 0):.4f} | >= 0.64 |",
        f"| Log Loss | {metrics.get('log_loss', 0):.4f} | <= 0.69 |",
        f"| Brier Score | {metrics.get('brier', 0):.4f} | <= 0.225 |",
        f"| AUROC | {metrics.get('auroc', 0):.4f} | — |",
        f"| ECE | {metrics.get('ece', 0):.4f} | <= 0.05 |",
        "",
        "## Single-Leg Hit Rate (edge > 5%, Step 11)",
        "",
        "Flat-bet win rate vs per-leg implied break-even. No parlay multiplier.",
        "See 'Parlay ROI' section below for walk-forward ROI with correct multipliers.",
        "",
        f"| Metric | Value |",
        f"|--------|-------|",
        f"| N Legs Selected | {metrics.get('n_bets', 0)} |",
        f"| Win Rate | {metrics.get('win_rate', 0):.3f} |",
        f"| Implied Break-Even | {metrics.get('implied', 0):.3f} |",
        f"| Edge over Implied | {metrics.get('edge', 0):+.3f} |",
        f"| Flat-Bet ROI | {metrics.get('flat_roi', 0):.3f} |",
        "",
        "## Target Floors",
        "",
        "| Check | Status |",
        "|-------|--------|",
        f"| Accuracy >= 0.64 | {'✓ PASS' if metrics.get('accuracy', 0) >= 0.64 else '✗ FAIL'} |",
        f"| Brier <= 0.225 | {'✓ PASS' if round(metrics.get('brier', 0), 4) <= 0.225 else '✗ FAIL'} |",
        f"| ECE <= 0.05 | {'✓ PASS' if metrics.get('ece', 0) <= 0.05 else '✗ FAIL'} |",
        "",
        "## Artifacts",
        "",
        "- `outputs/reports/calibration_winner.png` — Reliability diagram",
        "- `outputs/reports/roi_curve.png` — ROI vs edge threshold",
        "- `outputs/reports/pit_*.png` — Prop CDF calibration",
        "",
        f"_Generated by reportcard.py on {date.today()}_",
    ]

    # Step 11: Walk-forward parlay ROI
    parlay = metrics.get("parlay_roi")
    if parlay:
        p2 = parlay.get("2pick", {})
        p3 = parlay.get("3pick", {})
        thresh = parlay.get("threshold", 0.05)
        lines += [
            "",
            "## Parlay ROI — Walk-Forward (Step 11)",
            "",
            f"Each event's candidate legs (model_prob > implied + {thresh:.0%}) are",
            "combined into all 2-pick and 3-pick parlays independently. A parlay hits",
            "iff ALL legs win; payout = multiplier × stake if hit, else −stake.",
            "This is the correct ROI metric for Power Play power-play betting.",
            "",
            "| Parlay | N parlays | Hit rate | Expected hit | ROI | Multiplier |",
            "|--------|-----------|----------|-------------|-----|------------|",
        ]
        for key, pr, implied_note in [
            ("2pick", p2, f"~{p2.get('implied', 0)**2:.3f}"),
            ("3pick", p3, f"~{p3.get('implied', 0)**3:.3f}"),
        ]:
            n = pr.get("n_parlays", 0)
            hr = pr.get("hit_rate", 0.0)
            roi = pr.get("roi", 0.0)
            mult = pr.get("multiplier", 0.0)
            lines.append(
                f"| {key} | {n} | {hr:.3f} | {implied_note} | {roi:+.3f} | {mult:.1f}x |"
            )

    # Step 6: stability slices
    stab = metrics.get("stability_slices")
    if stab:
        slices = stab.get("slices", [])
        flags = stab.get("flags", [])
        lines += [
            "",
            "## Stability Slices (Step 6)",
            "",
            "Brier > 0.255 with n ≥ 50 triggers a flag. "
            "Bootstrap 95% CI shown; [within noise] = CI spans the threshold.",
            "WC slices use temperature-applied probabilities (matching inference).",
            "",
            "| Slice | n | Acc | Brier [95% CI] | ECE | Flag |",
            "|-------|---|-----|----------------|-----|------|",
        ]
        for s in slices:
            is_flagged = any(s["slice"] in f for f in flags)
            flag_str = "⚠️ HIGH" if is_flagged else ""
            ci_lo = s.get("brier_ci_lo")
            ci_hi = s.get("brier_ci_hi")
            if ci_lo is not None and ci_hi is not None:
                brier_str = f"{s['brier']:.3f} [{ci_lo:.3f}, {ci_hi:.3f}]"
            else:
                brier_str = f"{s['brier']:.3f}"
            lines.append(
                f"| {s['slice']} | {s['n']} | {s['acc']:.3f} | {brier_str} | {s['ece']:.3f} | {flag_str} |"
            )
        if flags:
            lines += ["", "### Flags", ""]
            for f in flags:
                lines.append(f"- {f}")

    with open(save_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"  Report written to {save_path}")


def write_prop_report(prop_results: dict[str, dict], save_path: Path) -> None:
    """Write prop calibration report with per-segment PIT KS section.

    Parameters
    ----------
    prop_results : dict[str, dict]
        Mapping of prop name -> result dict from pit_histogram_segmented.
        Each result dict has keys: ks_stat, ks_p, segments (optional).
        ``segments`` maps segment_name -> {ks_stat, ks_p, n}.
    save_path : Path
        Output markdown path.
    """
    save_path.parent.mkdir(parents=True, exist_ok=True)

    _TARGETS = {
        "sig_strikes":      ("< 0.04", 0.04),
        "takedowns":        ("< 0.04", 0.04),
        "r1_sig_strikes":   ("< 0.05", 0.05),
        "duration":         ("< 0.04", 0.04),
        "knockdowns":       ("< 0.05", 0.05),
        "sub_attempts":     ("< 0.05", 0.05),
        "r1_takedowns":     ("< 0.06", 0.06),
        "body_sig_strikes": ("< 0.04", 0.04),
        "leg_sig_strikes":  ("< 0.04", 0.04),
        "ctrl_time":        ("< 0.05", 0.05),
        "sig_strikes_combo":("< 0.05", 0.05),
    }
    # KO gate revised from 0.18 → 0.200 based on Brier decomposition (v8.2):
    # UNC=0.211, RES=0.007 — resolution floor means 0.18 was below achievable.
    # 0.200 requires RES≥0.011 (1.5× current), achievable with KO discrimination features.
    _KO_BRIER_GATE = 0.200

    lines = [
        f"# Prop Model Calibration Report — {date.today()}",
        "",
        "## Gate B — Overall PIT KS",
        "",
        "| Prop | KS stat | p-value | Target p | Status |",
        "|------|---------|---------|----------|--------|",
    ]

    for name, r in prop_results.items():
        ks = r.get("ks_stat", float("nan"))
        p = r.get("ks_p", float("nan"))
        target_str, threshold = _TARGETS.get(name, ("< 0.05", 0.05))
        status = "✓ PASS" if (not math.isnan(p) and p > 0.05) else "✗ FAIL"
        ks_str = f"{ks:.3f}" if not math.isnan(ks) else "n/a"
        p_str = f"{p:.4f}" if not math.isnan(p) else "n/a"
        lines.append(f"| {name} | {ks_str} | {p_str} | p > 0.05 | {status} |")

    lines += [
        "",
        "## Per-segment PIT",
        "",
        "KS statistics broken down by fight-outcome subgroup.",
        "Segments with n < 20 are omitted from KS computation (shown as n/a).",
        "",
    ]

    # Segments that are pure conditional-null diagnostics, not gates.
    # For r1_sig_strikes: the mixture-slice PIT is non-uniform by construction
    # (v8.8 principal review).  r1_end and past_r1 are now tested against valid
    # conditional CDFs (force_r1_end / force_full_round) and rendered as diagnostics.
    # For takedowns: 'finish' (KO+SUB realized fights) is a method-mixture-slice
    # artifact — the marginal forecast correctly averages over DEC (avg 1.24 TDs),
    # so slicing by realized finish is non-uniform by construction (same logic as
    # decision/past_r1). The realized-method conditional null scores each finish vs
    # its own KO/SUB forecast and shows KS≈0.027 (p≈0.92) — the model IS calibrated.
    _COND_NULL_SEGMENTS: dict[str, set[str]] = {
        "r1_sig_strikes": {"r1_end", "past_r1"},
        "takedowns": {"finish"},
    }
    _COND_NULL_NOTES: dict[str, str] = {
        "takedowns": (
            "`finish` is a realized-method conditional null (KO/SUB), not a marginal gate "
            "— the marginal method-mixture slice is non-uniform by construction "
            "(realized finishes exclude DEC, which avg 1.24 TDs vs KO 0.47 / SUB 1.09). "
            "Scored vs realized-method (KO/SUB) override forecast: KS≈0.027 (p≈0.92)."
        ),
    }
    for name, r in prop_results.items():
        segs = r.get("segments", {})
        if not segs:
            continue
        _diag_segs = _COND_NULL_SEGMENTS.get(name, set())
        _has_diag = bool(_diag_segs & segs.keys())
        lines += [
            f"### {name}",
            "",
        ]
        if _has_diag:
            lines.append(
                "_Note: segments marked (diag) are conditional-null diagnostics "
                "evaluated against F(count | regime), not the betting-relevant "
                "marginal. The Gate B overall KS is the pass/fail criterion._"
            )
            _prop_note = _COND_NULL_NOTES.get(name)
            if _prop_note:
                lines.append("")
                lines.append(f"_{_prop_note}_")
            lines.append("")
        lines += [
            "| Segment | n | KS stat | p-value | Status |",
            "|---------|---|---------|---------|--------|",
        ]
        for seg_name, s in segs.items():
            n = s.get("n", 0)
            sks = s.get("ks_stat", float("nan"))
            sp = s.get("ks_p", float("nan"))
            is_diag = seg_name in _diag_segs
            if math.isnan(sks):
                ks_str, p_str, status = "n/a", "n/a", "—"
            elif is_diag:
                ks_str = f"{sks:.3f}"
                p_str = f"{sp:.4f}"
                status = "🔬 diag"
            else:
                ks_str = f"{sks:.3f}"
                p_str = f"{sp:.4f}"
                status = "✓ PASS" if sp > 0.05 else "✗ FAIL"
            lines.append(f"| {seg_name} | {n} | {ks_str} | {p_str} | {status} |")
        lines.append("")

    # CRPS sharpness section (sig_strikes only, v8.10)
    _ss = prop_results.get("sig_strikes", {})
    _skill = _ss.get("crps_skill")
    if _skill is not None:
        _cm = _ss.get("crps_model", float("nan"))
        _cc = _ss.get("crps_clim", float("nan"))
        _skill_str = f"{_skill:.3f}"
        _outcome = "beats climatology [OK]" if _skill > 0 else "below climatology [WARN]"
        lines += [
            "## Sig Strikes — Sharpness (CRPS vs Climatology)",
            "",
            "CRPS energy form, train-set climatology stratified by scheduled_rounds.",
            "Skill > 0 confirms the forecast carries genuine betting edge.",
            "",
            "| Metric | Value |",
            "|--------|-------|",
            f"| CRPS (model) | {_cm:.3f} |",
            f"| CRPS (climatology) | {_cc:.3f} |",
            f"| Skill score (1 − model/clim) | {_skill_str} — {_outcome} |",
            "",
        ]

    lines += [
        "## Artifacts",
        "",
        "- `outputs/reports/pit_*_seg.png` — Segmented PIT histograms",
        "- `outputs/reports/pit_*.png` — Overall PIT histograms",
        "",
        f"_Generated by 05_evaluate_props.py on {date.today()}_",
    ]

    with open(save_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"  Prop report written to {save_path}")
